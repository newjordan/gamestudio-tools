"""Audit of ALL/class_map.json: where the raw-class -> shared `sem` mapping is inconsistent or uninformative.
Everything is computed from the map (per-class box counts `n` are the dataset-wide counts stored in the map)."""
import re
from collections import Counter, defaultdict

SEMS_ORDER = ["character", "enemy", "item", "prop", "decor", "vehicle", "building", "projectile", "fx", "ui", "card", "piece", "tile", "bg", "unknown"]


def family(name):
    """Family key of a raw class: lower-case, split on _ - . / space, drop trailing digits/ordinals; first two tokens
    when the first is generic (card, piece...) else first token. Used only to GROUP names that look related."""
    toks = [t for t in re.split(r"[_\-./ ]+", str(name).lower()) if t]
    toks = [re.sub(r"\d+$", "", t) for t in toks]
    toks = [t for t in toks if t]
    return toks[0] if toks else str(name)


def audit(cmap, min_boxes=200):
    """cmap: the 'map' dict source -> raw class -> {sem, rule, n}. Returns a dict of tables."""
    per_source = {}
    mixed = []
    for src, classes in cmap.items():
        sem_n, rules = Counter(), Counter()
        fam = defaultdict(lambda: defaultdict(list))
        total = 0
        for raw, v in classes.items():
            n = v.get("n", 0) or 0
            sem_n[v["sem"]] += n; rules[v.get("rule", "?")] += n; total += n
            fam[family(raw)][v["sem"]].append((raw, n))
        per_source[src] = {"classes": len(classes), "boxes": total, "sem_share": {s: sem_n[s] / total for s in sem_n} if total else {},
                           "unknown_share": sem_n["unknown"] / total if total else 0.0,
                           "top_rule": rules.most_common(1)[0] if rules else None}
        for f, sems in fam.items():
            if len(sems) > 1:
                n_by = {s: sum(n for _, n in lst) for s, lst in sems.items()}
                if sum(n_by.values()) >= min_boxes:
                    ex = {s: sorted(lst, key=lambda t: -t[1])[:3] for s, lst in sems.items()}
                    mixed.append({"source": src, "family": f, "boxes": sum(n_by.values()), "sems": n_by, "examples": ex})
    mixed.sort(key=lambda d: -d["boxes"])
    # same raw name, different sem across sources
    by_name = defaultdict(dict)
    for src, classes in cmap.items():
        for raw, v in classes.items():
            by_name[raw][src] = (v["sem"], v.get("n", 0) or 0)
    cross = []
    for raw, d in by_name.items():
        if len({s for s, _ in d.values()}) > 1 and sum(n for _, n in d.values()) >= min_boxes:
            cross.append({"raw": raw, "by_source": d, "boxes": sum(n for _, n in d.values())})
    cross.sort(key=lambda d: -d["boxes"])
    return {"per_source": per_source, "mixed_families": mixed, "cross_source": cross}


def render(a, top=15):
    L = ["# Class-map audit (generated by `python3 -m gbench classmap`)", "",
         "Source: `/workspace/gamedata/ALL/class_map.json` (raw class -> shared `sem`). Box counts are the dataset-wide counts stored in the map. Families group raw names by their first `_`-separated token with trailing digits removed; this is a heuristic to *find* suspicious spots, not a ground truth.", "",
         "## Share of boxes per sem, by source", "", "| source | classes | boxes | unknown | " + " | ".join(SEMS_ORDER[:-1]) + " | main rule |", "|---" * (4 + len(SEMS_ORDER)) + "|"]
    for src, d in sorted(a["per_source"].items(), key=lambda kv: -kv[1]["boxes"]):
        sh = d["sem_share"]
        L.append(f"| {src} | {d['classes']} | {d['boxes']:,} | {d['unknown_share']:.0%} | " + " | ".join(f"{sh.get(s, 0):.0%}" for s in SEMS_ORDER[:-1]) + f" | {d['top_rule'][0] if d['top_rule'] else ''} |")
    L += ["", f"## Raw-name families mapped to more than one sem (top {top} by boxes)", "", "| source | family | boxes | sem split (boxes) | examples |", "|---|---|---|---|---|"]
    for m in a["mixed_families"][:top]:
        sp = ", ".join(f"{s} {n:,}" for s, n in sorted(m["sems"].items(), key=lambda kv: -kv[1]))
        ex = "; ".join(f"{s}: " + ", ".join(r for r, _ in lst) for s, lst in m["examples"].items())
        L.append(f"| {m['source']} | `{m['family']}` | {m['boxes']:,} | {sp} | {ex} |")
    L += ["", f"## Same raw name, different sem in different sources (top {top} by boxes)", "", "| raw name | boxes | per source (sem, boxes) |", "|---|---|---|"]
    for c in a["cross_source"][:top]:
        L.append(f"| `{c['raw']}` | {c['boxes']:,} | " + ", ".join(f"{s}: {v[0]} ({v[1]:,})" for s, v in sorted(c["by_source"].items(), key=lambda kv: -kv[1][1])) + " |")
    return "\n".join(L) + "\n"


def render_changes(doc):
    ch = doc.get("changes") or []
    if not ch:
        return ""
    L = ["", "## v1.2 mapping changes", "",
         "Built from a snapshot of `ALL/class_map.json` (not modified). Every row has a measured box count `n` from that map and a source-metadata evidence string. Classes not listed are unchanged.",
         "", "| source | raw class | old sem | new sem | boxes | evidence |", "|---|---|---|---|---|---|"]
    for c in ch:
        ev = c.get("evidence","").replace("|","\\|")
        L.append(f"| {c['source']} | `{c['raw']}` | {c['old']} | {c['new']} | {c['n']:,} | {ev} |")
    L += ["", f"Total: {len(ch)} classes, {sum(c['n'] for c in ch):,} boxes remapped.", ""]
    return "\n".join(L)
