import json,os,csv,sys,re
sys.path.insert(0,'.')
from build_manifest import tree_sha
H='/workspace/gamedata-work/x_harvest'
inv={r['name']:r for r in csv.DictReader(open(f'{H}/loktar00_repo_inventory.csv'))}
rows=[]
def add(src_url,author,page,lic,proof,attr,typ,path,src,notes='',ai=False):
    p=f'{H}/{path}'
    if not os.path.exists(p): return
    s,n,sz=tree_sha(p)
    if n==0: return
    rows.append(dict(x_post_url=src_url,author_handle=author,asset_page_url=page,licence=lic,licence_proof_url=proof,attribution=attr,asset_type=typ,file_count=n,size_bytes=sz,sha256_tree=s,local_path=p,source=src,ai_generated=ai,notes=notes,round=3))
# Loktar repos
X='https://x.com/loktar00'
post={'sprite-stack-engine':'https://x.com/loktar00/status/2124260323427226003','sprite-stack-animation':'https://x.com/loktar00/status/2124286924835770662','sprite-stacking':'https://x.com/loktar00/status/2124940313932296470'}
ai={'sprite-stack-engine':True,'sprite-stacking':True,'codevember':True,'fog-demo':True}
likely={'hexbreach','lanternfall','pine-hollow','sled-free','sled-free-exact','zombie-sim','genetic-walker'}
for d,lab in [('assets/github_loktar','assets'),('reference/loktar00','reference')]:
    for n in sorted(os.listdir(f'{H}/{d}')):
        if not os.path.isdir(f'{H}/{d}/{n}'): continue
        r=inv[n]; sha=open(f'{H}/{d}/{n}.sha').read().strip()
        lic=r['licence']; nolic=lic=='none'
        proof=f"https://github.com/loktar00/{n}/blob/{sha}/LICENSE" if not nolic else f"https://github.com/loktar00/{n} (no licence file in repo at {sha[:10]})"
        notes=[]
        if nolic: notes.append('No licence file; reference-only copy in reference/ (not for redistribution).')
        if n in ai: notes.append('README states AI model authorship (e.g. code written by Claude / generated by DeepSeek V4 Flash / Claude Opus).')
        elif n in likely: notes.append("Likely LLM-built (author's stated practice: 'I test what models can build'); README does not say.")
        if n=='game-off-2012': notes.append('Fork; his Game Off 2012 entry.')
        if n=='atari7800dev': notes.append('Contains build output/ROM-related dev files for Atari 7800 homebrew.')
        add(post.get(n,X),'@loktar00',r['url'],lic if not nolic else 'none stated',proof,'Jason Brown (loktar00)',f"{r['category']}; {r['description'][:80]}",f'{d}/{n}','github (Loktar X profile links github.com/loktar00)',' '.join(notes),ai=(True if n in ai else ('likely' if n in likely else False)))
# Quaternius extra
for slug,page in [('150-lowpoly-nature-models','https://quaternius.itch.io/150-lowpoly-nature-models'),('fantasy-props-megakit','https://quaternius.itch.io/fantasy-props-megakit')]:
    add('https://x.com/loktar00' if False else '',"@quaternius",page,'CC0-1.0','https://quaternius.com/ (all packs CC0) + itch page','Quaternius - credit not required','3D models (kit zip)',f'assets/quaternius_itch/quaternius_{slug}','round-3 known-source expansion','Remaining small Quaternius itch kit; large megakits (downtown-city, medieval-village, sci-fi-essentials, modular-character-outfits) still deferred for size.')
# itch r3
chk={o['url']:o for o in json.load(open(f'{H}/r3/itch_check.json'))}
for d in sorted(os.listdir(f'{H}/assets/itch_r3')):
    u,slug=d.split('_',1); page=f'https://{u}.itch.io/{slug}'; c=chk.get(page,{})
    typ='font' if 'font' in slug else ('3D models' if any(k in slug for k in ['weapons','lo-fi']) else ('textures' if any(k in slug for k in ['texture','noise','abstract','y2k']) else '2D sprites/tiles/UI'))
    add('',f'@{u} (itch.io)',page,'CC0-1.0',f"{page} (Asset license: {c.get('lic')}; {c.get('ai')[:40] if c.get('ai') else ''})",f'{u} on itch.io - credit not required',typ,f'assets/itch_r3/{d}','itch.io public listing itch.io/game-assets/free/tag-cc0','Files over 25 MB per file skipped; some archives are .rar/.7z (not unpacked).' )
# OGA r3
for r in json.load(open(f'{H}/r3/oga_records.json')):
    if not r.get('ok') or not r.get('got'): continue
    d=os.path.dirname(r['got'][0]).replace(H+'/','')
    lic=re.match(r'(CC0|CC-BY-SA|CC-BY)',r['license']); lic=lic.group(1) if lic else r['license'][:20]
    add('',f"@{r['author']} (OpenGameArt)",r['page'],lic,r['page']+' (License(s) field)',f"By {r['author']} on OpenGameArt - credit not required for CC0",f"OpenGameArt {r['type']} submission",d,'opengameart.org top-CC0 search (items 7-11 per type)','Fetched at 10 s intervals.')
old=[json.loads(l) for l in open(f'{H}/manifest.jsonl')]
old=[o for o in old if o.get('round')!=3]
allr=old+rows
for r in allr: r.setdefault('round',1)
with open(f'{H}/manifest.jsonl','w') as f:
    for r in allr: f.write(json.dumps(r)+'\n')
keys=list(old[0])
with open(f'{H}/manifest.csv','w',newline='') as f:
    w=csv.DictWriter(f,fieldnames=keys); w.writeheader(); w.writerows(allr)
print(len(old),len(rows),round(sum(r['size_bytes'] for r in rows)/1e6,1),'MB r3')
import collections
c=collections.defaultdict(lambda:[0,0])
for r in rows: k=r['local_path'].replace(H+'/','').split('/')[0:2]; c['/'.join(k)][0]+=1;c['/'.join(k)][1]+=r['size_bytes']
for k,v in c.items(): print(k,v[0],round(v[1]/1e6,1))
l=collections.Counter(r['licence'] for r in rows); print(l)
