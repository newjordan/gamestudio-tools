#!/usr/bin/env python3
"""obj-bounds: report an OBJ's axis-aligned bounding box (min, max, size, centre, sphere
radius). Writes a JSON report to `-o`. Optional `--box` writes a 12-triangle OBJ of the
AABB (useful as a stand-in collider). The input mesh is never overwritten unless
`--in-place` (which would only apply if `-o` or `--box` points at the input).
"""
import argparse, os, json, math, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "obj-weld"))
import safe_out, obj_weld  # noqa: E402


def bounds_of(v):
    if v is None or len(v) == 0:
        raise SystemExit("no vertices in OBJ")
    vmin = v.min(axis=0)
    vmax = v.max(axis=0)
    size = vmax - vmin
    center = (vmin + vmax) / 2.0
    # radius of the bounding sphere about the centre (max corner distance)
    corners = []
    for x in (vmin[0], vmax[0]):
        for y in (vmin[1], vmax[1]):
            for z in (vmin[2], vmax[2]):
                corners.append(((x - center[0]) ** 2 + (y - center[1]) ** 2 + (z - center[2]) ** 2) ** 0.5)
    rec = {
        "min": [float(x) for x in vmin],
        "max": [float(x) for x in vmax],
        "size": [float(x) for x in size],
        "center": [float(x) for x in center],
        "radius": float(max(corners)),
        "vertices": int(len(v)),
    }
    return rec, vmin, vmax


def box_obj(vmin, vmax):
    # 8 corners, 12 triangles
    x0, y0, z0 = (float(x) for x in vmin)
    x1, y1, z1 = (float(x) for x in vmax)
    verts = [
        (x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
        (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1),
    ]
    # faces outward, CCW when viewed from outside
    faces = [
        (1, 2, 3), (1, 3, 4),  # z0
        (5, 8, 7), (5, 7, 6),  # z1
        (1, 5, 6), (1, 6, 2),  # y0
        (4, 3, 7), (4, 7, 8),  # y1
        (1, 4, 8), (1, 8, 5),  # x0
        (2, 6, 7), (2, 7, 3),  # x1
    ]
    lines = ["# AABB generated by obj-bounds"]
    for p in verts:
        lines.append(f"v {p[0]} {p[1]} {p[2]}")
    for a, b, c in faces:
        lines.append(f"f {a} {b} {c}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Report an OBJ bounding box (and optionally write an AABB mesh).")
    ap.add_argument("obj")
    ap.add_argument("-o", "--out", required=True, help="JSON report")
    ap.add_argument("--box", help="write a 12-triangle AABB OBJ")
    safe_out.add_flag(ap)
    a = ap.parse_args(argv)
    safe_out.check(a.obj, a.out, a.in_place)
    if a.box:
        safe_out.check(a.obj, a.box, a.in_place)
    v, _vt, _vn, _cmds, _prelude = obj_weld.load_obj(a.obj)
    rec, vmin, vmax = bounds_of(v)
    rec["out"] = a.out
    os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
    json.dump(rec, open(a.out, "w"), indent=1)
    if a.box:
        os.makedirs(os.path.dirname(os.path.abspath(a.box)) or ".", exist_ok=True)
        open(a.box, "w").write(box_obj(vmin, vmax))
        rec["box"] = a.box
    print(f"min {rec['min']} max {rec['max']} size {rec['size']} -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
    import cli_error
    sys.exit(cli_error.run(main))
